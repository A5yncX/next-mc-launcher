export const languages = {'zh-CN': '简体中文', en: 'English'};
export const languageKey = 'nextmc.language';

export function readLanguage() {
  try {
    const language = localStorage.getItem(languageKey);
    if (Object.hasOwn(languages, language)) return language;
  } catch { /* Use the WebView language when storage is unavailable. */ }
  return /^zh(?:-|$)/i.test(navigator.language) ? 'zh-CN' : 'en';
}

