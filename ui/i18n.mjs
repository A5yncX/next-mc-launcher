const patterns = Object.entries(english)
  .filter(([key]) => key.includes('{1}'))
  .map(([key, value]) => [new RegExp(`^${key.split(/\{\d+\}/).map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('([\\s\\S]+?)')}$`, 'u'), value]);

export function translate(language, text, ...args) {
  if (text == null) return text;
  if (args.length) {
    const template = language === 'en' && Object.hasOwn(english, text) ? english[text] : text;
    return template.replace(/\{(\d+)\}/g, (_, i) => args[i - 1]);
  }
  if (language !== 'en') return text;
  if (Object.hasOwn(english, text)) return english[text];
  for (const [pattern, template] of patterns) {
    const match = pattern.exec(text);
    if (match) return template.replace(/\{(\d+)\}/g, (_, i) => translate(language, match[i]));
  }
  return text;
}
